/** ISO 3166 alpha-2 → flag emoji (rendered with the Twemoji flag font on every OS). */
export function flag(code: string): string {
  return String.fromCodePoint(...code.toUpperCase().split("").map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

